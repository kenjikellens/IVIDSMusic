const fs = require('fs');
const path = require('path');

// Root directory of the project
const rootDir = path.resolve(__dirname, '../../');
const outputFilePath = path.join(rootDir, 'documentation', 'important_files.md');

// Directories to ignore (build output, caches, external modules)
const ignoredDirectories = new Set([
  '.git',
  '.gradle',
  '.idea',
  '.kotlin',
  '.vscode',
  'node_modules',
  'build',
  'dist',
  'gradle',
  '.agents'
]);

// File extensions to ignore (binaries, build artifacts, images)
const ignoredExtensions = new Set([
  '.apk',
  '.exe',
  '.jar',
  '.aar',
  '.class',
  '.pyc',
  '.log',
  '.tmp',
  '.png',
  '.jpg',
  '.jpeg',
  '.gif',
  '.ico',
  '.webp',
  '.zip',
  '.tar',
  '.gz'
]);

// Specific filenames to ignore
const ignoredFiles = new Set([
  'gradlew',
  'gradlew.bat',
  'local.properties',
  'package-lock.json',
  'yt-dlp.exe'
]);

/**
 * Checks whether a file or directory should be ignored.
 * @param {string} relativePath - The relative path of the file/directory from project root.
 * @param {string} fileName - The name of the file or directory.
 * @param {boolean} isDirectory - True if checking a directory, false for a file.
 * @returns {boolean} True if the item should be ignored.
 */
function shouldIgnore(relativePath, fileName, isDirectory) {
  if (isDirectory) {
    return ignoredDirectories.has(fileName);
  }
  
  if (ignoredFiles.has(fileName)) {
    return true;
  }
  
  const ext = path.extname(fileName).toLowerCase();
  if (ignoredExtensions.has(ext)) {
    return true;
  }
  
  return false;
}

/**
 * Recursively scans a directory for important project files.
 * @param {string} dirPath - Absolute path of directory to scan.
 * @param {string} relativeDir - Relative directory path from project root.
 * @returns {Array<{relativePath: string, fullPath: string, category: string}>} Array of file metadata objects.
 */
function scanDirectory(dirPath, relativeDir = '') {
  let results = [];
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });

  for (const entry of entries) {
    const entryRelative = relativeDir ? `${relativeDir}/${entry.name}` : entry.name;
    const entryFull = path.join(dirPath, entry.name);

    if (shouldIgnore(entryRelative, entry.name, entry.isDirectory())) {
      continue;
    }

    if (entry.isDirectory()) {
      results = results.concat(scanDirectory(entryFull, entryRelative));
    } else {
      const category = relativeDir ? relativeDir.split('/')[0] : 'Root';
      results.push({
        relativePath: entryRelative,
        fullPath: entryFull,
        category: category
      });
    }
  }

  return results;
}

/**
 * Formats the gathered file list into a structured markdown document using relative paths.
 * @param {Array<{relativePath: string, fullPath: string, category: string}>} files - List of scanned files.
 * @returns {string} The complete markdown content.
 */
function generateMarkdown(files) {
  const grouped = {};
  for (const file of files) {
    const cat = file.category;
    if (!grouped[cat]) {
      grouped[cat] = [];
    }
    grouped[cat].push(file);
  }

  let md = '# Important Project Files Index\n\n';
  md += '> [!NOTE]\n';
  md += '> This document is automatically generated by `.agents/scripts/generate-file-index.js`.\n';
  md += '> It provides a quick reference index of all core application, Kotlin/Android source, GUI, logic, script, and documentation files using relative links.\n\n';
  md += `Total important files listed: **${files.length}**\n\n`;

  const categories = Object.keys(grouped).sort((a, b) => {
    if (a === 'Root') return -1;
    if (b === 'Root') return 1;
    return a.localeCompare(b);
  });

  const docDir = path.dirname(outputFilePath);

  for (const category of categories) {
    md += `## ${category === 'Root' ? 'Root Files' : category + '/'}\n\n`;
    const sortedFiles = grouped[category].sort((a, b) => a.relativePath.localeCompare(b.relativePath));
    
    for (const file of sortedFiles) {
      const displayPath = `./${file.relativePath}`;
      let relativeLink = path.relative(docDir, file.fullPath).replace(/\\/g, '/');
      if (!relativeLink.startsWith('.')) {
        relativeLink = `./${relativeLink}`;
      }
      md += `- [${displayPath}](${relativeLink})\n`;
    }
    md += '\n';
  }

  return md;
}

/**
 * Main execution handler that triggers file scanning and writes output markdown file.
 */
function main() {
  console.log(`Scanning project root: ${rootDir}...`);
  const files = scanDirectory(rootDir);
  console.log(`Found ${files.length} important files.`);

  const mdContent = generateMarkdown(files);

  const docDir = path.dirname(outputFilePath);
  if (!fs.existsSync(docDir)) {
    fs.mkdirSync(docDir, { recursive: true });
  }

  fs.writeFileSync(outputFilePath, mdContent, 'utf-8');
  console.log(`Successfully generated index at: ${outputFilePath}`);
}

main();
